    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel)accountTable.getModel();
        int selectedRow = accountTable.getSelectedRow();

        if (selectedRow != -1) {
            int choice = javax.swing.JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete this account?",
                "Delete Account", javax.swing.JOptionPane.YES_NO_OPTION);

            if (choice == javax.swing.JOptionPane.YES_OPTION) {
                model.removeRow(selectedRow);

                boolean success = FileHandler.deleteRecord(model, "Account.txt");

                if (success) {
                    javax.swing.JOptionPane pane = new javax.swing.JOptionPane("Account deleted.",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE,
                        javax.swing.JOptionPane.DEFAULT_OPTION,
                        null, new Object[]{}, null);

                    javax.swing.JDialog dialog = pane.createDialog(this, "Delete Account");

                    javax.swing.Timer timer = new javax.swing.Timer(1000, tEvt -> dialog.dispose());
                    timer.setRepeats(false);
                    timer.start();

                    dialog.setVisible(true);
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error");
                }
            }
        }
        else {
            javax.swing.JOptionPane.showMessageDialog(this, "Select an account first.");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

