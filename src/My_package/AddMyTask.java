    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String subject = txtSubject.getText().trim();
        String task = txtTask.getText().trim();
        String dueDate = txtDueDate.getText().trim();
        String status = "Pending...";
        
        if (subject.isEmpty() || task.isEmpty() || dueDate.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Plese dont leave a blank.");
        } else {
            boolean isAdd = FileHandler.saveTask(this.studentId, subject, task, dueDate, status);
            
            if (isAdd) {
                javax.swing.JOptionPane pane = new javax.swing.JOptionPane("Task added successfully",
                javax.swing.JOptionPane.INFORMATION_MESSAGE,
                javax.swing.JOptionPane.DEFAULT_OPTION, null, new Object[]{}, null);
            
                javax.swing.JDialog dialog = pane.createDialog(this, "Success");
            
                javax.swing.Timer timer = new javax.swing.Timer(1000, tEvt -> dialog.dispose());
                timer.setRepeats(false);
                timer.start();
            
                dialog.setVisible(true);
                this.dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro.");
            }
        }
    }//GEN-LAST:event_btnAddActionPerformed

