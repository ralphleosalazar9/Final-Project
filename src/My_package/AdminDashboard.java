    private void boxOptionsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_boxOptionsActionPerformed
        String selectedOption = (String) boxOptions.getSelectedItem();
        
        if (selectedOption != null) {
            if (selectedOption.equals("Register")) {
                Register register = new Register();
                register.setVisible(true);
                this.dispose();
            } else if (selectedOption.equals("Accounts")) {
                AccountInfo accountInfo = new AccountInfo();
                accountInfo.setVisible(true);
                this.dispose();
            } else if (selectedOption.equals("Logout")) {
                LandPage landPage = new LandPage();
                landPage.setVisible(true);
                this.dispose();
            } else if (selectedOption.equals("Students")) {
                StudentInfo studentInfo = new StudentInfo();
                studentInfo.setVisible(true);
                this.dispose();
            }
        }
    }//GEN-LAST:event_boxOptionsActionPerformed

