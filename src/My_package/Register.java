    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) registerTable.getModel();
        int selectedRow = registerTable.getSelectedRow();
        
        if (selectedRow != -1) {
            int choice = javax.swing.JOptionPane.showConfirmDialog(this,
                    "Are you sure you want to register this?",
                    "Confirm Account", javax.swing.JOptionPane.YES_NO_OPTION);
            if (choice == javax.swing.JOptionPane.YES_OPTION) {
                try {
                    String targetId = model.getValueAt(selectedRow, 1).toString();
                    
                    boolean success = FileHandler.confirmRegister(targetId);
                    
                    if (success) {
                        model.removeRow(selectedRow);
                        
                        javax.swing.JOptionPane pane = new javax.swing.JOptionPane("Student successfuly registered.",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE,
                        javax.swing.JOptionPane.DEFAULT_OPTION,
                        null, new Object[]{}, null);
                    
                        javax.swing.JDialog dialog = pane.createDialog(this, "Registered");
                    
                        javax.swing.Timer timer = new javax.swing.Timer(1000, tEvt -> dialog.dispose());
                        timer.setRepeats(false);
                        timer.start();
                    
                        dialog.setVisible(true);
                    } else {
                        javax.swing.JOptionPane.showMessageDialog(this, "Error!");
                    }
                } catch (Exception e) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error on confirming account.");
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a student first.");
        }
        
    }//GEN-LAST:event_btnConfirmActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel)registerTable.getModel();
        int selectedRow = registerTable.getSelectedRow();
        
        if (selectedRow != -1) {
            int choice = javax.swing.JOptionPane.showConfirmDialog(this,
                    "Are you sure you want to delete this record?",
                    "Delete Record", javax.swing.JOptionPane.YES_NO_OPTION);
            
            if (choice == javax.swing.JOptionPane.YES_OPTION) {
                model.removeRow(selectedRow);
                
                boolean success = FileHandler.deleteRecord(model, "Register.txt");
                
                if (success) {
                    javax.swing.JOptionPane pane = new javax.swing.JOptionPane("Record deleted.",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE,
                    javax.swing.JOptionPane.DEFAULT_OPTION,
                    null, new Object[]{}, null);
                    
                    javax.swing.JDialog dialog = pane.createDialog(this, "Delete Record");
                    
                    javax.swing.Timer timer = new javax.swing.Timer(1000, tEvt -> dialog.dispose());
                    timer.setRepeats(false);
                    timer.start();
                    
                    dialog.setVisible(true);
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error.");
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a recorn first.");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

