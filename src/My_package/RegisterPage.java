    private void checkBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_checkBoxActionPerformed
        if (checkBox.isSelected()) {
            txtPassword.setEchoChar((char) 0);
            txtConfirmPassword.setEchoChar((char) 0);
        } else {
            txtPassword.setEchoChar('*');
            txtConfirmPassword.setEchoChar('*');
        }
    }//GEN-LAST:event_checkBoxActionPerformed

    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        String fullName = txtFullName.getText().trim();
        String idNumber = txtID.getText().trim();
        String password = txtPassword.getText().trim();
        String confirmPassword = txtConfirmPassword.getText().trim();
        
        if (fullName.isEmpty() || idNumber.isEmpty() || password.isEmpty() || confirmPassword.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Don't leave a blank.");
        } else if (!idNumber.matches("\\d+")) {
            javax.swing.JOptionPane.showMessageDialog(this, "ID Number should only contain intgers.");
        } else if (idNumber.length() != 6) {
            javax.swing.JOptionPane.showMessageDialog(this, "ID Number should only contains 6 digit.");
        } else if (!password.equals(confirmPassword)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Password don't match.");
        } else if (idNumber.equals("122206")) {
            javax.swing.JOptionPane.showMessageDialog(this, "This ID has already existed.");
        } else if (FileHandler.checkId(idNumber, "Register.txt") || FileHandler.checkId(idNumber, "Account.txt")) {
            javax.swing.JOptionPane.showMessageDialog(this, "This ID has already existed.");
        } else {
            AdminInput register = new AdminInput(fullName, idNumber, password);
            
            boolean isSaved = FileHandler.saveToRegister(register);
            
            if (isSaved) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                        "Account created successfully.\nPlease remember your ID and password.");
                javax.swing.JOptionPane.showMessageDialog(this, "Please wait for admins confirmation\nbefore you can login.");
                this.dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Error.");
            }
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

