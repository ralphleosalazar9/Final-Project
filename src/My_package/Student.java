    private void studentLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_studentLoginActionPerformed
        String idNumber = txtIdNumber.getText().trim();
        String password = txtPassword.getText().trim();
        
        String userRecord = FileHandler.getLoggedInUser(idNumber, password);
        
        if (userRecord != null) {
            String[] info = userRecord.split("\\|");
            String fullName = info[0].trim();
            String studentId = info[1].trim();
            
            StudentDashboard dashboard = new StudentDashboard(fullName, studentId);
            dashboard.setVisible(true);
            this.dispose();
        } else if (FileHandler.checkId(idNumber, "Register.txt")) {
            javax.swing.JOptionPane.showMessageDialog(this, "This account has not been\nconfirm by the admin.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid ID or password.");
        }
    }//GEN-LAST:event_studentLoginActionPerformed

